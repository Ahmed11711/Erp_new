<?php

/**
 * يولّد نماذج CSV بترميز UTF-16 LE + BOM، مع فصل الأعمدة بـ TAB (يعرض كل عمود في Excel بشكل صحيح).
 * تشغيل: php scripts/generate_inventory_csv_samples.php
 */

$base = dirname(__DIR__).'/../front-end/src/assets/inventory-import';

$t = "\t";

// صف رؤوس + صفّان أمثلة؛ الأعمدة الاختيارية بعد الحقول الإلزامية يمكن تركها فارغة.
$specs = [
    'items-sample.csv' =>
        implode($t, ['اسم الصنف', 'سعر التكلفة', 'المخزن', 'رقم الانتاج', 'رقم الوحدة', 'كود الصنف', 'اللون', 'المرجع', 'الحد الأدنى', 'فرع الانتاج'])."\r\n"
        .implode($t, ['صنف تجريبي أ', '25.5', 'مخزن مواد خام', '1', '1', 'DEMO-001', 'أحمر', '', '', ''])."\r\n"
        .implode($t, ['صنف تجريبي ب', '10', 'مخزن مواد خام', '1', '1', 'DEMO-002', '', 'REF-2', '5', ''])."\r\n",

    'opening-sample.csv' =>
        implode($t, ['اسم الصنف', 'الكمية', 'تكلفة الوحدة', 'المخزن', 'الكود', 'اللون', 'فرع الانتاج', 'رقم الوحدة', 'المرجع', 'الحد الأدنى'])."\r\n"
        .implode($t, ['صنف تجريبي أ', '100', '25.5', 'مخزن مواد خام', 'DEMO-001', 'أحمر', '', '', '', ''])."\r\n"
        .implode($t, ['صنف تجريبي ب', '50', '10', 'مخزن مواد خام', 'DEMO-002', '', '', '1', '', '2'])."\r\n",

    'adjustment-sample.csv' =>
        implode($t, ['اسم الصنف', 'الكمية الفعلية', 'المخزن', 'الكود', 'اللون', 'فرع الانتاج', 'رقم الوحدة', 'المرجع'])."\r\n"
        .implode($t, ['صنف تجريبي أ', '95', 'مخزن مواد خام', '', '', '', '', ''])."\r\n"
        .implode($t, ['صنف تجريبي ب', '48', 'مخزن مواد خام', '', '', '', '', ''])."\r\n",
];

foreach ($specs as $name => $utf8) {
    $path = $base.'/'.$name;
    $body = mb_convert_encoding($utf8, 'UTF-16LE', 'UTF-8');
    file_put_contents($path, "\xFF\xFE".$body);
    echo "Wrote UTF-16 LE + TAB: {$path}\n";
}
